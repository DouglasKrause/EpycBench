[[nodiscard]] consteval auto monitoring_q4_capacity_vocabulary_is_valid() -> bool {
    if (monitoring_q4_capacity_reasons.size() + 2U !=
        static_cast<std::size_t>(MonitoringQ4CapacityReason::count)) return false;
    for (std::size_t i{}; i < monitoring_q4_capacity_reasons.size(); ++i) {
        const auto& entry = monitoring_q4_capacity_reasons[i];
        if (static_cast<std::size_t>(entry.reason) != i + 2U || entry.code.size() > 80U ||
            !entry.code.starts_with("monitoring.q4.capacity.") || entry.code.back() == '.' || entry.code.find("..") != std::string_view::npos) return false;
        for (char c : entry.code)
            if (!((c >= 'a' && c <= 'z') || (c >= '0' && c <= '9') ||
                  c == '.' || c == '_' || c == '-')) return false;
        if (i && monitoring_q4_capacity_reasons[i - 1U].code >= entry.code) return false;
    }
    return true;
}
