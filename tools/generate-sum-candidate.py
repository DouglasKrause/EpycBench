#!/usr/bin/env python3
"""Render closed scalar Sum recipes and build their bounded compiler-option population."""

from __future__ import annotations

import argparse
import hashlib
import importlib.util
import json
from pathlib import Path
import shutil
import subprocess
import sys

ROOT = Path(__file__).resolve().parent.parent
PROFILE = "epycbench.generated-scalar-sum/v1"
COUNTS = (2, 8)
SEARCH_COUNT = 8
PACKAGE_MANIFEST = "epycbench.generated-sum-candidate/v3"
PACKAGE_ADAPTER = "modules/packages/sum_u64_implementation.cpp"

# An isolated Python invocation omits the script directory from sys.path.
_spec = importlib.util.spec_from_file_location("generated_sum_compiler_options",
                                               Path(__file__).with_name("generated_sum_compiler_options.py"))
_compiler_options = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(_compiler_options)
OPTIONS, compiler_option_facts = _compiler_options.OPTIONS, _compiler_options.compiler_option_facts


def candidate_suffix(count: int, option: str | None) -> str:
    return f"a{count}-align32" if option == "align32" else f"a{count}"


def implementation(count: int, option: str | None) -> str:
    return f"generated-scalar-u64-sum-{candidate_suffix(count, option)}/v1"


def render(count: int, option: str | None) -> str:
    declarations = "\n".join(f"        std::uint64_t a{index}{{}};" for index in range(count))
    loads = "\n".join(
        f"            a{index} += epycbench::module_detail::load_sum_word(request->data, index + {index}U);"
        for index in range(count)
    )
    fold = " + ".join(f"a{index}" for index in range(count))
    return f'''// Generated by {PROFILE}; accumulators=unroll={count}.
#include "task_module_support.hpp"

extern "C" [[gnu::visibility("default"), gnu::noinline]] auto epycbench_kernel_execute_v2(
    const EpycBenchKernelRequestV2* request, std::uint64_t* checksum) noexcept -> int {{
    if (!checksum || epycbench::module_detail::prepare_sum_u64(request) != 0) return 1;
    const auto count = static_cast<std::size_t>(request->bytes / sizeof(std::uint64_t));
    std::uint64_t folded{{}};
    for (std::uint64_t repetition{{}}; repetition < request->repetitions; ++repetition) {{
        asm volatile("" ::: "memory");
{declarations}
        std::size_t index{{}};
        for (; count - index >= {count}U; index += {count}U) {{
{loads}
        }}
        for (; index < count; ++index)
            a0 += epycbench::module_detail::load_sum_word(request->data, index);
        folded += {fold};
    }}
    asm volatile("" ::: "memory");
    *checksum = folded;
    return 0;
}}
'''
def digest(path: Path) -> str:
    result = hashlib.sha256()
    with path.open("rb") as source:
        for block in iter(lambda: source.read(1024 * 1024), b""):
            result.update(block)
    return result.hexdigest()


def write(path: Path, text: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8")


def command_path(command: dict, field: str) -> Path:
    path = Path(command[field])
    return (Path(command["directory"]) / path).resolve()


def manifest(arguments: argparse.Namespace) -> dict:
    source = arguments.source.resolve()
    option = arguments.compiler_option
    if source.read_text(encoding="utf-8") != render(arguments.accumulators, option):
        raise ValueError("Generated source does not match the closed recipe")
    commands = json.loads(arguments.compile_commands.read_text(encoding="utf-8"))
    selected = [command for command in commands if command_path(command, "file") == source]
    if len(selected) != 1:
        raise ValueError("Expected exactly one actual CMake compile command for this source")
    report = json.loads(arguments.check.read_text(encoding="utf-8"))
    module_hash = digest(arguments.module)
    if (report.get("schema") != "epycbench.basic-kernel-check/v1"
            or report.get("status") not in ("pass", "warning")
            or report.get("module_sha256") != module_hash):
        raise ValueError("Basic check does not admit the exact linked module")
    inputs = ["modules/task_module_support.hpp", "modules/module_support.hpp", "modules/leaf_requests.hpp"]
    inputs += ["include/epycbench/kernel/package.h", PACKAGE_ADAPTER,
               "modules/packages/task_u64_support.hpp", "modules/output_task_module_support.hpp"]
    result = {
        "schema": PACKAGE_MANIFEST,
        "generator": {"profile": PROFILE, "sha256": digest(Path(__file__))},
        "recipe": {"accumulators": arguments.accumulators, "unroll": arguments.accumulators},
        "task_id": "task.sum.u64/v1",
        "implementation_id": implementation(arguments.accumulators, option),
        "abi_version": 1,
        "source": {"file": str(source), "sha256": digest(source)},
        "project_inputs": {name: digest(ROOT / name) for name in inputs},
        "compile_command": selected[0],
        "toolchain": {"compiler": str(arguments.compiler.resolve()),
                      "compiler_sha256": digest(arguments.compiler),
                      "id": arguments.compiler_id, "version": arguments.compiler_version,
                      "target": arguments.compiler_target, "preset": arguments.preset},
        "module": {"file": str(arguments.module.resolve()), "sha256": module_hash},
        "basic_check": {"file": str(arguments.check.resolve()), "sha256": digest(arguments.check),
                        "status": report["status"]},
    }
    if option:
        helper = "tools/generated_sum_compiler_options.py"
        result["project_inputs"][helper] = digest(ROOT / helper)
        result["compiler_option"] = compiler_option_facts(option, selected[0], arguments.compiler_id)
    else:
        result["recipe"]["candidate_population"] = list(COUNTS)
    # Both translation units belong to the same CMake target. Other Sum
    # implementations compile the same adapter into their own objects.
    target_directory = command_path(selected[0], "output")
    target = next((p for p in target_directory.parents if p.parent.name == "CMakeFiles"), None)
    adapters = [command for command in commands if command_path(command, "file") == ROOT / PACKAGE_ADAPTER
                and target in command_path(command, "output").parents]
    if len(adapters) != 1:
        raise ValueError("Expected exactly one adapter compile command in the generated target")
    result["adapter_compile_command"] = adapters[0]
    if option and compiler_option_facts(option, adapters[0], arguments.compiler_id) != result["compiler_option"]:
        raise ValueError("Generated body and package adapter must use the same compiler option")
    return result


def write_manifest(arguments: argparse.Namespace) -> None:
    receipt = manifest(arguments)
    write(arguments.output, json.dumps(receipt, indent=2, sort_keys=True) + "\n")
    toolchain = receipt["toolchain"]
    provenance = {"receipt_sha256": digest(arguments.output), "module_sha256": receipt["module"]["sha256"],
                  "source_sha256": receipt["source"]["sha256"], "basic_check": receipt["basic_check"]["sha256"],
                  "generator": receipt["generator"], "recipe": receipt["recipe"],
                  "toolchain": {field: toolchain[field] for field in
                                ("compiler_sha256", "id", "version", "target", "preset")}}
    if "compiler_option" in receipt:
        provenance["compiler_option"] = receipt["compiler_option"]
    package = {"schema": "epycbench.kernel/v1", "id": receipt["implementation_id"],
               "task": "sum-u64.task.yaml", "module": arguments.module.name, "tuning": {}, "build": provenance}
    # JSON syntax is a subset of the restricted YAML grammar and needs no extra dependency.
    write(arguments.package_manifest, json.dumps(package, indent=2) + "\n")


def run_build_step(directory: Path, step: dict) -> bool:
    with (directory / step["log"]).open("wb") as log:
        try:
            completed = subprocess.run(step["command"], cwd=ROOT, stdout=log, stderr=subprocess.STDOUT)
        except OSError as error:
            step["error"] = str(error)
            return False
    step["return_code"] = completed.returncode
    return completed.returncode == 0


def candidate_artifacts(build: Path, entry: dict) -> dict[str, str]:
    stem = "sum-u64-generated-" + candidate_suffix(SEARCH_COUNT, entry["compiler_option"])
    module_dir = build / "generated-sum-compiler-search" / "kernel-packages"
    manifest_path = module_dir / (stem + ".candidate.json")
    manifest_data = manifest_path.read_bytes()
    recorded = json.loads(manifest_data)
    module_path = module_dir / (stem + ".so")
    check_path = module_dir / (stem + ".kernel-check.json")
    module_hash, check_hash = digest(module_path), digest(check_path)
    if (recorded["schema"] != PACKAGE_MANIFEST
            or recorded["implementation_id"] != entry["implementation_id"]
            or recorded["compiler_option"]["id"] != entry["compiler_option"]
            or recorded["module"]["sha256"] != module_hash or recorded["basic_check"]["sha256"] != check_hash):
        raise ValueError("Generated build artifacts differ from the candidate manifest")
    artifacts = {str(path.relative_to(build.parent)): checksum for path, checksum in (
        (module_path, module_hash), (check_path, check_hash),
        (manifest_path, hashlib.sha256(manifest_data).hexdigest()),
    )}
    metadata = module_dir / (stem + ".kernel.yaml")
    binding = json.loads(metadata.read_bytes())
    if (binding["id"] != entry["implementation_id"] or binding["task"] != "sum-u64.task.yaml"
            or binding["module"] != module_path.name or binding["build"]["module_sha256"] != module_hash
            or binding["build"]["receipt_sha256"] != digest(manifest_path)):
        raise ValueError("Generated kernel package differs from its compiler receipt")
    artifacts[str(metadata.relative_to(build.parent))] = digest(metadata)
    return artifacts


def build_search(preset: str, directory: Path, budget: int) -> int:
    directory = directory.resolve()
    directory.mkdir(mode=0o700)
    build = directory / "build"
    build_command = ["cmake", "--build", str(build), "--parallel", "1", "--target"]
    baseline_target = "epycbench_generated_sum_package_baselines"
    module_directory = "kernel-packages"
    preparation = [
        {"command": ["cmake", "--preset", preset, "-B", str(build)], "log": "configure.log"},
        {"command": [*build_command, baseline_target], "log": "baselines.log"},
    ]
    candidates = []
    for index, (option, flags) in enumerate(OPTIONS.items()):
        target = f"epycbench_generated_sum_search_{option.replace('-', '_')}_module"
        target += "_package"
        candidates.append({"compiler_option": option, "flags": flags,
                           "implementation_id": implementation(SEARCH_COUNT, option),
                           "status": "unattempted" if index < budget else "outside_budget",
                           "command": [*build_command, target], "log": f"{option}.log"})
    record = {"schema": "epycbench.generated-sum-build-search/v2", "preset": preset,
              "accumulators": SEARCH_COUNT, "build_attempt_budget": budget, "charged_build_attempts": 0,
              "preparation": preparation, "candidates": candidates, "module_directory": None}
    receipt = directory / "build-search.json"

    def save() -> None:
        temporary = receipt.with_suffix(".tmp")
        write(temporary, json.dumps(record, indent=2) + "\n")
        temporary.replace(receipt)

    save()
    for step in preparation:
        succeeded = run_build_step(directory, step)
        save()
        if not succeeded:
            print(f"Generated Sum preparation failed. See {receipt} and {step['log']}.", file=sys.stderr)
            return 1

    admitted = []
    for attempt in candidates[:budget]:
        attempt["status"] = "reserved"
        record["charged_build_attempts"] += 1
        save()
        succeeded = run_build_step(directory, attempt)
        if succeeded:
            try:
                attempt["artifacts"] = candidate_artifacts(build, attempt)
            except (OSError, ValueError, KeyError) as error:
                attempt["error"] = str(error)
            else:
                admitted.append(attempt)
        attempt["status"] = "admitted" if "artifacts" in attempt else "failed"
        save()

    if admitted:
        bundle = directory / "staged-modules"
        shutil.copytree(build / "generated-sum" / module_directory, bundle)
        for attempt in admitted:
            for name, checksum in attempt["artifacts"].items():
                source = directory / name
                copied = bundle / source.name
                shutil.copy2(source, copied)
                if digest(copied) != checksum:
                    raise ValueError(f"Published artifact differs from the candidate receipt: {copied.name}")
        bundle.rename(directory / module_directory)
        record["module_directory"] = module_directory
        save()

    print(f"Generated Sum admitted {len(admitted)} of {record['charged_build_attempts']} charged attempts. See {receipt}.")
    return int(len(admitted) != budget)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    actions = parser.add_subparsers(dest="action", required=True)
    for name in ("render", "manifest"):
        action = actions.add_parser(name)
        action.add_argument("--accumulators", type=int, choices=COUNTS, required=True)
        action.add_argument("--compiler-option", choices=OPTIONS)
        action.add_argument("--source", type=Path, required=True)
        if name == "manifest":
            for field in ("module", "check", "compile-commands", "compiler", "output"):
                action.add_argument(f"--{field}", type=Path, required=True)
            for field in ("compiler-id", "compiler-version", "compiler-target", "preset"):
                action.add_argument(f"--{field}", required=True)
            action.add_argument("--package-manifest", type=Path, required=True)
    search = actions.add_parser("build-search", help="Build candidates in a fresh directory with a fixed attempt budget")
    search.add_argument("--preset", required=True)
    search.add_argument("--directory", type=Path, required=True)
    search.add_argument("--build-budget", type=int, choices=range(1, len(OPTIONS) + 1), required=True)
    arguments = parser.parse_args()
    if arguments.action == "build-search":
        try:
            return build_search(arguments.preset, arguments.directory, arguments.build_budget)
        except (OSError, ValueError) as error:
            print(f"Generated Sum build search failed: {error}", file=sys.stderr)
            return 1
    if arguments.compiler_option and arguments.accumulators != SEARCH_COUNT:
        parser.error("The closed compiler-option population uses eight accumulators")
    if arguments.action == "render":
        write(arguments.source, render(arguments.accumulators, arguments.compiler_option))
    else:
        write_manifest(arguments)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
