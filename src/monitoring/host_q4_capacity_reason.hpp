[[nodiscard]] constexpr auto monitoring_q4_capacity_reason_entry(
    MonitoringQ4CapacityReason reason) noexcept -> const MonitoringQ4CapacityReasonEntry* {
    const auto index = static_cast<std::size_t>(reason);
    return index >= 2U && index - 2U < monitoring_q4_capacity_reasons.size()
        ? &monitoring_q4_capacity_reasons[index - 2U] : nullptr;
}
[[nodiscard]] constexpr auto monitoring_q4_capacity_reason_code(
    MonitoringQ4CapacityReason reason) noexcept -> std::optional<std::string_view> {
    if (reason == MonitoringQ4CapacityReason::unspecified)
        return "monitoring.q4.capacity";
    if (const auto* entry = monitoring_q4_capacity_reason_entry(reason))
        return entry->code;
    return std::nullopt;
}
[[nodiscard]] constexpr auto monitoring_q4_capacity_reason_matches(
    MonitoringQ4CapacityReason reason,
    std::initializer_list<MonitoringQ4CapacityReasonFamily> families) noexcept -> bool {
    if (reason == MonitoringQ4CapacityReason::unspecified)
        return true;
    const auto* entry = monitoring_q4_capacity_reason_entry(reason);
    if (!entry) return false;
    for (auto family : families) if (entry->family == family) return true;
    return false;
}
[[nodiscard]] constexpr auto monitoring_q4_capacity_code_is_valid(std::string_view code) noexcept
    -> bool {
    if (code == "monitoring.q4.capacity") return true;
    for (const auto& entry : monitoring_q4_capacity_reasons)
        if (entry.code == code) return true;
    return false;
}
